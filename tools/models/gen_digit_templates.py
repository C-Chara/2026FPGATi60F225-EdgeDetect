"""Write src/edge/digit_templates.v: the digit_reader templates (Arial Bold,
digits 0-9 at -8, 0, +8 degrees) as a combinational ROM indexed by
t = 3 * digit + rotation: bits (dark cells) and care (cells that count;
coverage 0.3..0.7 is don't care). Cell k = row * GW + column, bit k.

Usage: gen_digit_templates.py <project_dir>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import digit_study as ds     # noqa: E402

GW, GH = 7, 9


def word(bits):
    v = 0
    for k, b in enumerate(bits):
        if b:
            v |= 1 << k
    return v


def main(root):
    tm = ds.templates(GW, GH)
    n = GW * GH
    lines = ['`timescale 1ns/1ps', '',
             '// Generated by tools/models/gen_digit_templates.py (Arial Bold, %dx%d grid).' % (GW, GH),
             '// Template t = 3 * digit + rotation (-8, 0, +8 degrees); bit k = cell row*%d+col.' % GW,
             'module digit_templates (', '    input  wire [4:0]  t,',
             '    output reg  [%d:0] bits,' % (n - 1), '    output reg  [%d:0] care' % (n - 1), ');',
             '    always @* begin', '        case (t)']
    order = [(d, r) for d in '0123456789' for r in ds.ROTS]
    for i, key in enumerate(order):
        lines.append("            5'd%d: begin bits = %d'h%x; care = %d'h%x; end   // %s %+d" % (
            i, n, word(tm[key][0]), n, word(tm[key][1]), key[0], key[1]))
    lines += ["            default: begin bits = %d'h0; care = %d'h0; end" % (n, n),
              '        endcase', '    end', 'endmodule', '']
    path = os.path.join(root, 'src', 'edge', 'digit_templates.v')
    open(path, 'w', newline='\r\n').write('\n'.join(lines))
    print('wrote', path)
    for key in [('4', 0), ('1', 0)]:
        b, c, _ = tm[key]
        print(key)
        for j in range(GH):
            print('  ' + ''.join(('#' if b[j * GW + i] else '.') if c[j * GW + i] else '?' for i in range(GW)))


if __name__ == '__main__':
    main(sys.argv[1])
